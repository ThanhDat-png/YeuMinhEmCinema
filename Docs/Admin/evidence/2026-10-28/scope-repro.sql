USE YeuMinhEmCinema_Test;
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET QUOTED_IDENTIFIER ON;
IF DB_NAME() NOT LIKE '%[_]Test' THROW 50980,N'Test database required',1;
BEGIN TRY
BEGIN TRAN;
DECLARE @tag varchar(32)='audit_'+LEFT(REPLACE(CONVERT(varchar(36),NEWID()),'-',''),12),@actor int,@nv int,@a int,@b int,@room int,@kind int,@seat int;
INSERT dbo.TaiKhoan(TenDangNhap,MatKhauHash) VALUES(@tag,REPLICATE('X',80)); SET @actor=SCOPE_IDENTITY();
INSERT dbo.TaiKhoanVaiTro SELECT @actor,MaVaiTro FROM dbo.VaiTro WHERE TenVaiTro='QUAN_LY';
INSERT dbo.VaiTroQuyen SELECT MaVaiTro,'RAP_QUAN_LY' FROM dbo.VaiTro v WHERE TenVaiTro='QUAN_LY' AND NOT EXISTS(SELECT 1 FROM dbo.VaiTroQuyen q WHERE q.MaVaiTro=v.MaVaiTro AND q.MaQuyen='RAP_QUAN_LY');
INSERT dbo.NhanVien(MaTaiKhoan,HoTen) VALUES(@actor,N'Audit manager');SET @nv=SCOPE_IDENTITY();
INSERT dbo.Rap(TenRap,TrangThai) VALUES(@tag+'_A',N'Đang hoạt động'); SET @a=SCOPE_IDENTITY();
INSERT dbo.Rap(TenRap,TrangThai) VALUES(@tag+'_B',N'Đang hoạt động'); SET @b=SCOPE_IDENTITY();
INSERT dbo.NhanVienRap VALUES(@nv,@a),(@nv,@b);
INSERT dbo.PhongChieu(MaRap,TenPhong,DinhDang,TrangThai) VALUES(@b,N'Audit room',N'2D',N'Đang hoạt động');SET @room=SCOPE_IDENTITY();
INSERT dbo.LoaiGhe(TenLoai) VALUES(@tag);SET @kind=SCOPE_IDENTITY();
INSERT dbo.Ghe(MaPhong,HangGhe,SoGhe,MaLoaiGhe,TrangThai) VALUES(@room,'A',1,@kind,N'Hoạt động');SET @seat=SCOPE_IDENTITY();
DELETE dbo.NhanVienRap WHERE MaNhanVien=@nv AND MaRap=@b;
SELECT dbo.fn_YMC_CoPhamViRap(@actor,@b) AS ScopeAfterRevocation;
EXEC dbo.sp_YMC_LuuRap @NguoiThucHien=@actor,@MaRap=@b,@TenRap=N'CHANGED OUTSIDE SCOPE',@TrangThai=N'Đang hoạt động';
IF EXISTS(SELECT 1 FROM dbo.Rap WHERE MaRap=@b AND TenRap=N'CHANGED OUTSIDE SCOPE') PRINT N'FOUND: manager can update cinema after its assignment was revoked';
EXEC dbo.sp_YMC_LuuPhong @NguoiThucHien=@actor,@MaPhong=@room,@MaRap=@b,@TenPhong=N'CHANGED OUTSIDE SCOPE',@DinhDang=N'2D',@TrangThai=N'Đang hoạt động';
IF EXISTS(SELECT 1 FROM dbo.PhongChieu WHERE MaPhong=@room AND TenPhong=N'CHANGED OUTSIDE SCOPE') PRINT N'FOUND: manager can update room after its assignment was revoked';
DECLARE @seats dbo.YMC_DanhSachGhe;INSERT @seats VALUES(@seat);
EXEC dbo.sp_YMC_CapNhatLoGhe @NguoiThucHien=@actor,@Ghe=@seats,@TrangThai=N'Hỏng/Ngừng sử dụng';
IF EXISTS(SELECT 1 FROM dbo.Ghe WHERE MaGhe=@seat AND TrangThai=N'Hỏng/Ngừng sử dụng') PRINT N'FOUND: manager can update seat after its assignment was revoked';
ROLLBACK;
PRINT N'All audit fixtures rolled back';
END TRY BEGIN CATCH IF @@TRANCOUNT>0 ROLLBACK;THROW; END CATCH;